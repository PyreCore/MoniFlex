/// Drapeau emoji correspondant à la devise (pays = 2 premières lettres du
/// code ISO, avec quelques exceptions pour les devises régionales).
String currencyFlag(String code) {
  const special = {
    'EUR': '🇪🇺',
    'XAF': '🌍',
    'XOF': '🌍',
    'XCD': '🌎',
    'XPF': '🌏',
    'XDR': '🏦',
    'ANG': '🇨🇼',
  };
  if (special.containsKey(code)) return special[code]!;
  if (code.length < 2) return '🏳️';
  final cc = code.substring(0, 2).toUpperCase();
  return String.fromCharCodes(cc.codeUnits.map((c) => 0x1F1E6 + c - 65));
}
